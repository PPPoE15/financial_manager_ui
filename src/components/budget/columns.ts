// NOTE(FM-43): полное название — в подсказке `title`, а на тач-устройствах её не вызвать: на телефоне длинное
// название целиком видно только в окне «Редактирование категорий».
// z-index закреплённых ячеек задаёт строка (`LAYER_CLASS`): у итоговой он выше, чем у статей под ней.
// NOTE(FM-43): ширины «Плана» и «Среднего» рассчитаны на суммы до ~999 999 999 ₽ (план статьи — не больше
