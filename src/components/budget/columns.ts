/** Сколько символов названия статьи видно в таблице; длиннее — обрезается с многоточием. */
export const CATEGORY_NAME_MAX = 20

/**
 * Текст ячейки названия ограничен шириной колонки (200 − 24px отступа): 20 символов широкими буквами
 * («ШШШ…») длиннее — их обрезает CSS.
 */
export const CATEGORY_NAME_CLASS = 'block sm:max-w-[176px] sm:truncate'

/**
 * Слои ячеек по колонкам: для шапки и строк статей (`row`) и для итоговой строки (`total`). z-index — без
 * префикса ширины (у незакреплённой ячейки он ни на что не влияет), чтобы порядок слоёв был один на любом
 * экране: «Сумма» над «Планом» и «Средним» итога (незакреплённые, они уезжают под неё), те — над месяцами,
 * а вся итоговая строка — над строками статей, которые прокручиваются под неё.
 */
// TODO(FM-43): `sticky`/`left` ячейки — в `COLUMN_CLASS`, а её z-index — в `LAYER_CLASS.row`; каждый `th`
// шапки склеивает обе карты вручную, и у новой закреплённой ячейки легко забыть z-index. Держать z-10 в
// `COLUMN_CLASS`, а в `LAYER_CLASS` оставить только итог.
export const LAYER_CLASS = {
  row: { category: 'z-10', plan: 'z-10', average: 'z-10', month: '' },
  total: {
    category: 'sticky bottom-0 z-30',
    plan: 'sticky bottom-0 z-20',
    average: 'sticky bottom-0 z-20',
    month: 'sticky bottom-0 z-10 bg-surface-card',
  },
} as const

/** Класс колонки месяца по индексу 0–11: перед январём — вертикальный разделитель. */
export function monthColumnClass(index: number): string {
  return index === 0 ? COLUMN_CLASS.january : COLUMN_CLASS.month
}
