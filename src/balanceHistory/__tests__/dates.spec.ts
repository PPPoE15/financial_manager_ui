import { describe, expect, it } from 'vitest'
import { moscowToday, validateRange } from '../dates'

/** Проверяет календарь и включительную длину диапазона. */
describe('Даты истории остатка', () => {
  /** Проверяет смену дня независимо от часового пояса компьютера. */
  it('считает сегодня по Москве', () => {
    expect(moscowToday(new Date('2026-10-25T21:00:00Z'))).toBe('2026-10-26')
    expect(moscowToday(new Date('2026-10-25T20:59:59Z'))).toBe('2026-10-25')
  })
  /** Принимает один день и ровно 366 дней високосного года. */
  it.each([
    ['2024-02-29', '2024-02-29'],
    ['2024-01-01', '2024-12-31'],
  ])(
    'принимает %s — %s',
    /** Проверяет допустимый диапазон. */
    (from, to) => expect(validateRange(from, to, '2026-10-26')).toBe(''),
  )
  /** Отсекает неправильные даты, порядок, длину и будущие дни. */
  it.each([
    ['', '2026-10-26'],
    ['2026-02-29', '2026-03-01'],
    ['2026-04-31', '2026-05-01'],
    ['1999-12-31', '2000-01-01'],
    ['2100-01-01', '2100-01-01'],
    ['2026-10-26', '2026-10-25'],
    ['2024-01-01', '2025-01-01'],
    ['2026-10-26', '2026-10-27'],
    ['2026-1-01', '2026-01-02'],
  ])(
    'отклоняет %s — %s',
    /** Проверяет ошибку у недопустимого диапазона. */
    (from, to) => expect(validateRange(from, to, '2026-10-26')).not.toBe(''),
  )
})
